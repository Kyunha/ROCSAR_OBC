std::vector<std::complex<int16_t>> generate_signal_tx(const Config& cfg)
{
    const double SAMPLE_RATE = cfg.fs;
    const double PRF         = cfg.prf;

    // Number of active pulse samples defined by the static array
    const size_t tx_samps  = sizeof(TXSignal) / sizeof(TXSignal[0]); // 1137 samples
    const size_t pri_samps = static_cast<size_t>(SAMPLE_RATE / PRF);

    // Full PRI buffer initialized with zeros (pulse followed by listening silence)
    std::vector<std::complex<int16_t>> sig(pri_samps, {0, 0});

    // Directly access the .I and .Q members from the cs16 union
    const size_t copy_samps = tx_samps;
    for (size_t i = 0; i < copy_samps; ++i) 
    {
        sig[i] = std::complex<int16_t>(TXSignal[i].I, TXSignal[i].Q);
    }

    std::cout << "[Signal] Chirp samples : " << copy_samps << "\n"
              << "[Signal] PRI samples   : " << pri_samps << "\n"
              << "[Signal] Tx samples  : " << tx_samps << " samples\n"
              << "[Signal] Silence       : " << (pri_samps > copy_samps ? pri_samps - copy_samps : 0) << " samples\n";

    return sig;
}